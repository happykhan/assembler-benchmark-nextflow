import assert from 'node:assert/strict';
import {compareTableValues, matchesTableFilters} from './table-controls.js';
assert.ok(compareTableValues('9,000 bp','20,000 bp') < 0);
assert.ok(compareTableValues('30.2 s','8.0 s') > 0);
assert.ok(compareTableValues('contig_2','contig_10') < 0);
assert.ok(compareTableValues('Not recorded','4',-1) > 0, 'Missing stays last in either direction');
assert.ok(compareTableValues('Not reported','30.0',-1) > 0, 'Contig missing coverage stays last');
assert.ok(matchesTableFilters('Genome W Flye Pass', {tool:'Flye',status:'Pass'}, 'w flye', {tool:'Flye',status:'Pass'}));
assert.ok(!matchesTableFilters('Genome W Flye Pass', {tool:'Flye',status:'Pass'}, 'w', {status:'Fail'}));
assert.ok(!matchesTableFilters('Genome W Flye Pass', {}, 'w raven', {}));
assert.ok(matchesTableFilters('Genome W Flye Pass', {}, '  W   PASS ', {}));
console.log('Table helpers passed: natural/numeric sorting, missing values, combined search and filters.');
